/**
 * Grounding check for the corpus golden set.
 * Questions must be backed by a phrase that still exists in the uploaded note.
 * Not-found questions must use a token that is absent from all four notes.
 * This does not call a model and does not score live retrieval.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { describe, expect, it } from "vitest";

type Grounding = { title: string; phrase: string };

type GoldenItem = {
  id: string;
  category: string;
  user_input: string;
  reference: string;
  expectTitles: string[];
  forbidTitles: string[];
  grounding?: Grounding[];
  absent?: string;
};

const NOTES = [
  "哈佛家训-读书笔记",
  "活下去的理由-读书笔记",
  "天才在左疯子在右-读书笔记",
  "不要挑战人性-读书笔记",
  "带壳的牡蛎是大人的心脏-读书笔记",
  "黑匣子思维-读书笔记",
  "脱胎换骨的人生整理术-读书笔记",
  "正午之魔-读书笔记",
] as const;

const PDF_TITLES = [
  "frostbite_creamery_annual_financial_statement (full grid)",
  "sample-pdf-100kb",
  "sample-pdf-2mb",
  "sample-pdf-5mb",
  "sample-pdf-10mb",
  "sample-pdf-500kb",
  "sample-pdf-small",
  "sample-pdf-tiny",
] as const;

const MARKERS: Record<(typeof NOTES)[number], string> = {
  "哈佛家训-读书笔记": "《哈佛家训》",
  "活下去的理由-读书笔记": "《活下去的理由》",
  "天才在左疯子在右-读书笔记": "《天才在左 疯子在右》",
  "不要挑战人性-读书笔记": "《不要挑战人性》",
  "带壳的牡蛎是大人的心脏-读书笔记": "《带壳的牡蛎是大人的心脏》",
  "黑匣子思维-读书笔记": "《黑匣子思维",
  "脱胎换骨的人生整理术-读书笔记": "《脱胎换骨的人生整理术",
  "正午之魔-读书笔记": "《正午之魔",
};

const LOCAL_PDF: Record<string, string> = {
  "frostbite_creamery_annual_financial_statement (full grid)":
    "df25ad26-279a-4e13-b522-d28d4aed8487.pdf",
  "sample-pdf-100kb": "e14e111f-f70f-4307-b824-d249cf22e03c.pdf",
  "sample-pdf-2mb": "21f692a7-b6c2-40a6-ab7c-9e77f34f6a38.pdf",
  "sample-pdf-5mb": "3c0e03da-11eb-4bb4-83af-66d416b4a23d.pdf",
  "sample-pdf-10mb": "f603155b-1336-4fa8-93a2-39234a901a92.pdf",
};

const BLOB_PDF_EXTRACT: Record<string, string> = {
  "sample-pdf-500kb": "Sample Mixed Content\nChapter 1 of 20 · flipperfile.com",
  "sample-pdf-small": "Page 1 of 3 · Generated by Flipper File",
  "sample-pdf-tiny": "Page 1 of 1 · Generated by Flipper File",
};

const __dirname = dirname(fileURLToPath(import.meta.url));
const golden = JSON.parse(readFileSync(join(__dirname, "golden.json"), "utf8")) as GoldenItem[];
const uploadsDir = join(__dirname, "../../../uploads");

function loadNotes(): Record<string, string> | null {
  if (!existsSync(uploadsDir)) return null;
  const texts = readdirSync(uploadsDir)
    .filter((name) => name.endsWith(".md"))
    .map((name) => readFileSync(join(uploadsDir, name), "utf8"));
  const byTitle: Record<string, string> = {};
  for (const title of NOTES) {
    const text = texts.find((body) => body.includes(MARKERS[title]));
    if (!text) return null;
    byTitle[title] = text;
  }
  return byTitle;
}

describe("corpus golden set", () => {
  it("has 100 questions across the enterprise categories", () => {
    expect(golden).toHaveLength(138);
    const ids = new Set(golden.map((item) => item.id));
    expect(ids.size).toBe(138);
    const questions = new Set(golden.map((item) => item.user_input));
    expect(questions.size).toBe(138);

    const counts = new Map<string, number>();
    for (const item of golden) {
      counts.set(item.category, (counts.get(item.category) ?? 0) + 1);
      expect(item.user_input.length).toBeGreaterThan(0);
      expect(item.reference.length).toBeGreaterThan(0);
      for (const title of [...item.expectTitles, ...item.forbidTitles]) {
        expect([...NOTES, ...PDF_TITLES]).toContain(title);
      }
      for (const forbidden of item.forbidTitles) {
        expect(item.expectTitles).not.toContain(forbidden);
      }
    }

    expect(counts.get("basic")).toBe(52);
    expect(counts.get("semantic")).toBe(26);
    expect(counts.get("intra_doc")).toBe(16);
    expect(counts.get("cross_doc")).toBe(16);
    expect(counts.get("constrained")).toBe(12);
    expect(counts.get("not_found")).toBe(8);
    expect(counts.get("pdf_extract")).toBe(8);
  });

  const notes = loadNotes();

  it.skipIf(!notes)("every cited phrase is still in the uploaded note", async () => {
    const bodies = notes!;
    for (const item of golden) {
      if (item.category === "not_found") {
        expect(item.expectTitles).toEqual([]);
        expect(item.absent && item.absent.length > 0).toBe(true);
        for (const body of Object.values(bodies)) {
          expect(body.includes(item.absent!)).toBe(false);
        }
        continue;
      }
      expect(item.grounding && item.grounding.length > 0).toBe(true);
      const groundedTitles = new Set<string>();
      for (const piece of item.grounding!) {
        const body =
          bodies[piece.title] ??
          (LOCAL_PDF[piece.title] && existsSync(join(uploadsDir, LOCAL_PDF[piece.title]))
            ? readFileSync(join(uploadsDir, LOCAL_PDF[piece.title]))
            : undefined) ??
          BLOB_PDF_EXTRACT[piece.title];
        expect(body, piece.title).toBeTruthy();
        if (LOCAL_PDF[piece.title] && existsSync(join(uploadsDir, LOCAL_PDF[piece.title]))) {
          const { PDFParse } = await import("pdf-parse");
          const parser = new PDFParse({ data: readFileSync(join(uploadsDir, LOCAL_PDF[piece.title])) });
          const parsed = await parser.getText();
          await parser.destroy();
          expect(parsed.text).toContain(piece.phrase);
        } else {
          expect(String(body)).toContain(piece.phrase);
        }
        groundedTitles.add(piece.title);
      }
      for (const title of item.expectTitles) {
        expect(groundedTitles.has(title)).toBe(true);
      }
    }
  });
});
